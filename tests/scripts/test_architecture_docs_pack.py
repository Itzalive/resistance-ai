"""The AI pack (spec 2026-11-17-architecture-docs-design.md, "AI pack" and "Writers", Pack text)."""

from __future__ import annotations

import json

from arch_delta_support import DOCS_LIB, call, lib_url, require_node, run_module

require_node()

MARKER = "<!-- Generated by architecture-docs from the architecture model. Do not edit. -->"


def text_fn(fn: str, *args) -> object:
    result = call("pack-text.mjs", fn, *args, lib=DOCS_LIB)
    assert result["ok"], result
    return result["value"]


def test_pack_one_line_fields_lose_line_feeds() -> None:  # Pack text; AC-25 (a title on one line)
    assert text_fn("oneLine", "Orders\nand\nmore") == "Orders and more"


def test_pack_multi_line_fields_keep_lines_and_guard_headings() -> None:  # Pack text; AC-25
    text = "Use A.\n# Heading\n---\n--- x\nkeep # this\n-- two\n#"
    assert text_fn("multiLine", text) == "Use A.\n\\# Heading\n\\---\n\\--- x\nkeep # this\n-- two\n\\#"


def test_pack_text_leaves_ids_and_markup_unescaped() -> None:  # Pack text: written as export gives them
    assert text_fn("oneLine", "shop.web [x](y) *z* <b> a_b | c") == "shop.web [x](y) *z* <b> a_b | c"
    assert text_fn("multiLine", "a_b | c\n`d`") == "a_b | c\n`d`"


def test_pack_file_layout() -> None:  # Pack layout; AC-13 (marker line)
    assert text_fn("packFile", "front: Front\nend", ["## Elements", "### a: A\nkind system"]) == (
        MARKER + "\n\n# front: Front end\n\n## Elements\n\n### a: A\nkind system\n"
    )


def test_pack_file_with_no_parts() -> None:  # Pack layout: an empty section is left out
    assert text_fn("packFile", "Architecture pack", []) == MARKER + "\n\n# Architecture pack\n"

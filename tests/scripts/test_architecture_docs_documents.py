def decision(id_: str, **over) -> dict:
    record = {"id": id_, "decision": "Decide " + id_ + ".", "reason": "Because.", "rejected": [], "binds": [], "status": "current",
              "evidence": "spec", "sources": ["docs/x.md"]}
    record.update(over)
    return record


